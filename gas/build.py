#!/usr/bin/env python3
"""GAS (GED Awesome Slides) - builds a project into a self-contained,
servable/deployable site directory. See gas/README.md for the framework,
gas/CLAUDE.md for how to write slides and exercises with it.

    python3 gas/build.py <project> <site-dir>            build once
    python3 gas/build.py <project> <site-dir> --watch     rebuild on every change

<project> is a source directory holding sections/ and, alongside it, a
config.js (see gas/README.md for its shape) - never touched by the build,
so it stays pure source, safe to treat as 100% hand-authored. <site-dir> is
where the build writes everything needed to serve or deploy the result:

    <site-dir>/index.html                  a redirect to the project below
    <site-dir>/<project's own name>/        the built page, plus a copy of
                                            the project's own config.js,
                                            style.css and assets/
    <site-dir>/gas/assets/                 a copy of this framework's assets

<site-dir> is disposable - delete it any time, rebuild recreates it whole.

The page shell is gas/template.html, shared by every project. Three
placeholders in it receive that project's sections, each in its own slot:

    <!-- build:decks -->      every <div class="deck">, in the stage
    <!-- build:projects -->   every <article class="project">, the exercise pages
    <!-- build:views -->      every other <section class="view">, the screens

A fourth, <!-- build:palettes -->, becomes one <link> per file under
gas/assets/palettes/ - see discover_palettes() below, or gas/README.md for
the shape one of those files needs.

A section is a folder of <project>/sections/, and every .html file in it is
one entry of the sidebar: a deck, an exercise page or a screen. The build
reads the class of the file's first element to pick its slot, and pastes the
file as it is, so the code samples keep their whitespace. Folders and files
come in name order, which is why the folders are numbered like the sidebar.

An exercise page written as markdown keeps it in a .md file next to its
wrapper, and pulls it in with

    <!-- build:markdown dashboard.md -->

The build turns that into the <script type="text/markdown"> app.js renders
from: a page opened from a file:// url cannot fetch a .md file of its own, so
the text has to ride inside the page.

The template references its own assets as `{{gas}}/assets/...` - since the
built project and the copied gas/ always end up as siblings directly under
<site-dir>, that's always just `../gas`, regardless of where <project> and
this gas/ directory actually live on disk.

Only the standard library is used.
"""

import re
import shutil
import sys
import time
from pathlib import Path

GAS_DIR = Path(__file__).resolve().parent
TEMPLATE = GAS_DIR / "template.html"
GAS_REL = "../gas"  # site-dir/<project>/index.html -> site-dir/gas, always one level up

SLOTS = ("decks", "projects", "views")
SLOT_OF_CLASS = {"deck": "decks", "project": "projects", "view": "views"}

# a project's own static files, copied alongside the page it built - not
# every project has all of these (style.css is optional, see gas/README.md)
PROJECT_STATIC = ("config.js", "style.css", "assets")

PLACEHOLDER = re.compile(r"^[ \t]*<!-- build:(decks|projects|views) -->[ \t]*\n", re.M)
PALETTES_PLACEHOLDER = re.compile(r"^[ \t]*<!-- build:palettes -->[ \t]*\n", re.M)
MARKDOWN = re.compile(r"^([ \t]*)<!-- build:markdown (\S+) -->[ \t]*$", re.M)
COMMENT = re.compile(r"<!--.*?-->", re.S)
FIRST_TAG = re.compile(r"<([a-zA-Z][^>]*)>")
CLASS = re.compile(r'\bclass="([^"]*)"')

HEADER = (
    "<!-- Generated by gas/build.py from gas/template.html and this project's\n"
    "     sections/. Do not edit this file: edit those, then rebuild -->\n"
)


class BuildError(Exception):
    pass


def slot_of(source, path, sections_dir):
    """the slot a section file goes to, from the class of its first element"""
    tag = FIRST_TAG.search(COMMENT.sub("", source))
    classes = CLASS.search(tag.group(1)) if tag else None
    kind = classes.group(1).split()[0] if classes and classes.group(1).split() else None
    if kind not in SLOT_OF_CLASS:
        raise BuildError(
            f"{path.relative_to(sections_dir.parent)}: the first element must be a "
            f'<div class="deck">, an <article class="project"> or a <section class="view">'
        )
    return SLOT_OF_CLASS[kind]


def include_markdown(source, path, project):
    """each build:markdown directive becomes the script tag holding the file.
    Returns (new_source, md_rel_path) - md_rel_path is the .md file's own
    path (relative to the project), or None if this section has no
    build:markdown directive at all. See stamp_source below for why."""
    md_rel = None

    def replace(match):
        nonlocal md_rel
        indent, name = match.groups()
        md_path = path.parent / name
        if not md_path.is_file():
            raise BuildError(f"{path.relative_to(project)}: no file {name} next to it")
        text = md_path.read_text(encoding="utf-8")
        if "</script" in text:
            raise BuildError(f"{md_path.relative_to(project)}: '</script' would end the page's script tag")
        md_rel = md_path.relative_to(project).as_posix()
        return f'{indent}<script type="text/markdown">\n{text.rstrip()}\n{indent}</script>'

    return MARKDOWN.sub(replace, source), md_rel


FIRST_OPEN_TAG = re.compile(r"<(article|section|div)\b")


def stamp_source(source, rel_path, kind):
    """Adds data-src/data-src-kind to a section's root element - the editor
    (app.js, talking to dev.py's save API) uses it to know which file on disk,
    and in what shape, a slide/project/view's content actually came from.
    kind is "html-block" (this very tag, found again by its data-id, is what
    a save replaces) or "markdown-file" (rel_path is the .md file a
    build:markdown directive pulled in - the whole file is the editable unit,
    the wrapping tag itself is never touched)."""
    escaped = rel_path.replace('"', "&quot;")
    return FIRST_OPEN_TAG.sub(
        lambda m: f'{m.group(0)} data-src="{escaped}" data-src-kind="{kind}"',
        source,
        count=1,
    )


def discover_palettes():
    """one <link> per assets/palettes/*.css file, sorted by name - "claude"
    is the always-there default (see that file itself), any other is a
    project opting into GAS's own theme picker with nothing to register:
    just drop a self-contained [data-palette="name"] (+ [data-theme="dark"])
    stylesheet in that folder and it's discovered here, next build. Each
    carries data-palette so app.js can list what's available straight off
    the DOM, without a separate manifest to keep in sync with the folder."""
    palettes_dir = GAS_DIR / "assets" / "palettes"
    files = sorted(palettes_dir.glob("*.css")) if palettes_dir.is_dir() else []
    if not files:
        raise BuildError(f"no palette (a data-palette .css file) under {palettes_dir}")
    return "\n".join(
        f'<link rel="stylesheet" data-palette="{f.stem}" href="{GAS_REL}/assets/palettes/{f.name}">'
        for f in files
    )


def sync(src, dst):
    """replaces dst with a fresh copy of src - a file or a directory, and
    only if src actually exists (a project need not have every optional
    static file). Always a full replace, not a merge: a since-deleted file
    or image should not linger in the built output either."""
    if not src.exists():
        return
    if dst.exists():
        shutil.rmtree(dst) if dst.is_dir() else dst.unlink()
    if src.is_dir():
        shutil.copytree(src, dst)
    else:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def build(project_dir, site_dir):
    """writes a full site to <site-dir> (see the module docstring for its
    shape), and returns the number of section files the project holds"""
    project = Path(project_dir).resolve()
    sections = project / "sections"
    site = Path(site_dir).resolve()
    out = site / project.name

    if not TEMPLATE.is_file():
        raise BuildError(f"no template at {TEMPLATE}")
    template = TEMPLATE.read_text(encoding="utf-8")
    found = set(PLACEHOLDER.findall(template))
    missing = [slot for slot in SLOTS if slot not in found]
    if missing:
        raise BuildError(f"template.html lacks the placeholder(s): {', '.join(missing)}")
    if not PALETTES_PLACEHOLDER.search(template):
        raise BuildError("template.html lacks the <!-- build:palettes --> placeholder")

    if not sections.is_dir():
        raise BuildError(f"no sections/ under {project}")
    files = sorted(sections.glob("*/*.html"))
    if not files:
        raise BuildError(f"no section files under {sections}")
    slots = {slot: [] for slot in SLOTS}
    for path in files:
        source, md_rel = include_markdown(path.read_text(encoding="utf-8"), path, project)
        rel_path = path.relative_to(project).as_posix()
        source = stamp_source(source, md_rel or rel_path, "markdown-file" if md_rel else "html-block")
        entry = f"<!-- {rel_path} -->\n{source.strip(chr(10))}\n"
        slots[slot_of(source, path, sections)].append(entry)

    palettes = discover_palettes()
    page = template.replace("{{gas}}", GAS_REL)
    page = PALETTES_PLACEHOLDER.sub(palettes + "\n", page)
    page = PLACEHOLDER.sub(lambda m: "\n".join(slots[m.group(1)]), page)
    doctype, newline, rest = page.partition("\n")

    out.mkdir(parents=True, exist_ok=True)
    (out / "index.html").write_text(doctype + newline + HEADER + rest, encoding="utf-8")
    for name in PROJECT_STATIC:
        sync(project / name, out / name)
    sync(GAS_DIR / "assets", site / "gas" / "assets")
    (site / "index.html").write_text(
        f'<!doctype html><meta http-equiv="refresh" content="0; url={project.name}/index.html">\n'
        f"<a href=\"{project.name}/index.html\">{project.name}/index.html</a>\n",
        encoding="utf-8",
    )
    return len(files)


def snapshot(project_dir):
    """what the sources are right now: their paths and modification times -
    the project (now pure source, never holding any generated output) and
    this framework's own assets, so a style.css/app.js edit is picked up
    the same way a section edit is"""
    project = Path(project_dir).resolve()
    seen = {}
    for path in (TEMPLATE, *project.rglob("*"), *(GAS_DIR / "assets").rglob("*")):
        try:
            if path.is_file():
                seen[path] = path.stat().st_mtime_ns
        except OSError:
            pass  # gone between the listing and the stat: the next poll sees it
    return seen


def report(message):
    print(f"{time.strftime('%H:%M:%S')}  {message}", flush=True)


def watch(project_dir, site_dir):
    last = None
    while True:
        current = snapshot(project_dir)
        if current != last:
            last = current
            try:
                report(f"built {site_dir} from {build(project_dir, site_dir)} section files")
            except BuildError as error:
                report(f"not built: {error}")
        time.sleep(0.5)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) < 2:
        sys.exit("usage: build.py <project-dir> <site-dir> [--watch]")
    project_dir, site_dir = args[0], args[1]
    if "--watch" in sys.argv[1:]:
        try:
            watch(project_dir, site_dir)
        except KeyboardInterrupt:
            print()
    else:
        try:
            print(f"built {site_dir} from {build(project_dir, site_dir)} section files")
        except BuildError as error:
            sys.exit(f"build.py: {error}")


if __name__ == "__main__":
    main()
